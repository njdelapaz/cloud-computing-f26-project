#!/usr/bin/env python3
"""Write config/policies.conf from the policy mapping in SPEC §6.

Each policy mixes fairness (F), balance (B) and utilization (U) with coefficients c_F, c_B, c_U:
  ordering:  Fairshare = round(c_F * fs_scale), Age = total - Fairshare
  placement: Spread = c_B / (c_B + c_U), Fit = 1 - Spread   (both 0 when c_B + c_U = 0: stock placement)
BASE is the stock-style reference: fixed ordering weights and stock placement.

P4 tunes the parameters below; rerun this script afterwards instead of editing policies.conf by hand.
Usage: make_policies.py [--out config/policies.conf] [--check]
  --check  exit 1 if the file on disk differs from what the parameters produce
"""
import argparse
import sys
from pathlib import Path

VER02 = Path(__file__).resolve().parent.parent

TOTAL = 100_000            # ordering weights of every policy sum to this (SPEC §5)
FS_SCALE = 90_000          # Fairshare for c_F = 1; Age keeps the rest, so it never drops below 10k
SPLIT = (0.6, 0.3, 0.1)    # coefficients for the 1st, 2nd and 3rd metric of an ordered composite
BASE = {"Fairshare": 70_000, "Age": 20_000, "JobSize": 10_000}


def coefficients():
    yield "F", {"F": 1.0, "B": 0.0, "U": 0.0}
    yield "B", {"F": 0.0, "B": 1.0, "U": 0.0}
    yield "U", {"F": 0.0, "B": 0.0, "U": 1.0}
    for order in ("FBU", "FUB", "BFU", "BUF", "UFB", "UBF"):
        yield ">".join(order), dict(zip(order, SPLIT))
    yield "EQ", {"F": 1 / 3, "B": 1 / 3, "U": 1 / 3}


def line(name, fairshare, age, jobsize, spread, fit):
    return (f"PolicyName={name:<6} Fairshare={fairshare:<6} Age={age:<6} JobSize={jobsize:<6} "
            f"Spread={spread:.6f} Fit={fit:.6f}")


def render():
    out = ["# Generated by scripts/make_policies.py from the SPEC §6 mapping. Don't edit by hand:",
           "# change the parameters in the script and rerun it.",
           f"# total={TOTAL} fs_scale={FS_SCALE} split={'/'.join(str(s) for s in SPLIT)}",
           line("BASE", BASE["Fairshare"], BASE["Age"], BASE["JobSize"], 0.0, 0.0)]
    for name, c in coefficients():
        fairshare = round(c["F"] * FS_SCALE)
        placement = c["B"] + c["U"]
        spread = round(c["B"] / placement, 6) if placement > 0 else 0.0
        fit = round(1.0 - spread, 6) if placement > 0 else 0.0
        out.append(line(name, fairshare, TOTAL - fairshare, 0, spread, fit))
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(VER02 / "config" / "policies.conf"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    path = Path(a.out).resolve()
    shown = path.relative_to(VER02) if path.is_relative_to(VER02) else path
    if a.check:
        same = path.exists() and path.read_text() == text
        print(f"{shown}: {'up to date' if same else 'OUT OF DATE (rerun make_policies.py)'}")
        sys.exit(0 if same else 1)
    path.write_text(text)
    print(f"wrote {shown}")


if __name__ == "__main__":
    main()
